function obaApplyLang(lang) {
  const dict = window.OBA_TRANSLATIONS[lang];
  if (!dict) return;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    if (dict[key] !== undefined) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    el.dataset.i18nAttr.split(';').forEach((pair) => {
      const [attr, key] = pair.split(':').map(s => s.trim());
      if (attr && dict[key] !== undefined) el.setAttribute(attr, dict[key]);
    });
  });
  document.querySelectorAll('.oba-lang-btn').forEach((btn) => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
  var claveTitulo = document.documentElement.dataset.titleKey;
  if (claveTitulo && dict[claveTitulo] !== undefined) document.title = dict[claveTitulo];
  document.documentElement.lang = lang;
  try { localStorage.setItem('oba_lang', lang); } catch (e) {}
}

function obaInit() {
  let saved = 'es';
  try { saved = localStorage.getItem('oba_lang') || 'es'; } catch (e) {}
  obaApplyLang(saved);

  document.querySelectorAll('.oba-lang-btn').forEach((btn) => {
    btn.addEventListener('click', () => obaApplyLang(btn.dataset.lang));
  });

  var menuBtn = document.querySelector('.oba-page .oba-menu-btn');
  var inlineMenu = document.querySelector('.oba-page #oba-inline-menu');
  if (menuBtn && inlineMenu) {
    menuBtn.addEventListener('click', function () {
      var isOpen = inlineMenu.classList.toggle('open');
      menuBtn.classList.toggle('active', isOpen);
      menuBtn.setAttribute('aria-expanded', String(isOpen));
    });
  }

  obaInitMaridajes();
}

// Pestañas de la sección Maridajes
function obaInitMaridajes() {
  var tabs = Array.prototype.slice.call(document.querySelectorAll('.oba-maridaje-tab'));
  var paneles = Array.prototype.slice.call(document.querySelectorAll('.oba-maridaje-panel'));
  if (!tabs.length) return;

  function mostrar(id, mover) {
    tabs.forEach(function (t) {
      var on = t.dataset.maridaje === id;
      t.classList.toggle('activo', on);
      t.setAttribute('aria-selected', String(on));
      t.tabIndex = on ? 0 : -1;
      if (on && mover) t.focus();
    });
    paneles.forEach(function (p) {
      var on = p.dataset.maridaje === id;
      p.classList.toggle('activo', on);
      p.hidden = !on;
    });
  }

  tabs.forEach(function (tab, i) {
    tab.addEventListener('click', function () { mostrar(tab.dataset.maridaje, false); });
    tab.addEventListener('keydown', function (e) {
      var salto = e.key === 'ArrowRight' ? 1 : e.key === 'ArrowLeft' ? -1 : 0;
      if (!salto) return;
      e.preventDefault();
      var siguiente = tabs[(i + salto + tabs.length) % tabs.length];
      mostrar(siguiente.dataset.maridaje, true);
    });
  });
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', obaInit);
} else {
  obaInit();
}
